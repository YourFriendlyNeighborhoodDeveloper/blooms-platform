#!/usr/bin/env bash
# Runs the staging demonstration: the real application, worker and PostgreSQL in Docker on this
# machine, at https://localhost:8443. Publishing it to the internet is a separate, deliberate step.
#
#   scripts/staging.sh up            build, start locally, and load the fictional demo data once
#   scripts/staging.sh publish       also serve it on a public trycloudflare.com address (exposes this machine)
#   scripts/staging.sh unpublish     stop serving it publicly
#   scripts/staging.sh url           print the current address
#   scripts/staging.sh resync        follow a new public address after the tunnel restarted
#   scripts/staging.sh status        containers, health, and the public address
#   scripts/staging.sh reset [--yes] wipe the staging database and load fresh demo data
#   scripts/staging.sh backup        write a database backup to deploy/staging/backups now
#   scripts/staging.sh restore-check restore the newest backup into a scratch database and check it
#   scripts/staging.sh verify        run the browser checks against the running deployment
#   scripts/staging.sh logs [svc]    follow logs
#   scripts/staging.sh down          stop everything, keeping the data
#
# Secrets live in deploy/staging/.env.staging and sign-in details in deploy/staging/access.txt.
# Both are created on first run, readable only by you, and never committed.
set -euo pipefail
cd "$(dirname "$0")/.."

DIR=deploy/staging
ENV_FILE=$DIR/.env.staging
ACCESS=$DIR/access.txt
LOCAL_URL=https://localhost:8443

dc() { docker compose -p blooms-staging -f "$DIR/compose.yml" --env-file "$ENV_FILE" --profile public "$@"; }
secret() { openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | cut -c1-"$1"; }
get_env() { grep -E "^$1=" "$ENV_FILE" | head -1 | cut -d= -f2-; }
set_env() {
  local tmp
  tmp=$(mktemp)
  awk -v k="$1" -v v="$2" 'BEGIN { done = 0 } index($0, k "=") == 1 { print k "=" v; done = 1; next } { print } END { if (!done) print k "=" v }' "$ENV_FILE" > "$tmp"
  chmod 600 "$tmp"
  mv "$tmp" "$ENV_FILE"
}

ensure_env() {
  [ -f "$ENV_FILE" ] && return
  umask 077
  local pg session demo mailbox
  pg=$(secret 32); session=$(secret 64); demo=$(secret 20); mailbox=$(secret 20)
  cat > "$ENV_FILE" <<EOF
# Staging only. Generated by scripts/staging.sh. Never commit this file.
APP_ENV=staging
PUBLIC_BASE_URL=$LOCAL_URL
SESSION_SECRET=$session
POSTGRES_PASSWORD=$pg
DATABASE_URL=postgres://blooms:$pg@db:5432/blooms
TRUST_PROXY=cloudflare
SITE_MODE=preview
PAYMENTS_MODE=mock
EMAIL_PROVIDER=smtp
SMTP_URL=smtp://mailpit:1025
EMAIL_FROM=orders@demo.example
MESSAGE_ALLOWLIST=@demo.example,abraxastechnologies@gmail.com
SMS_ENABLED=false
STORAGE_PROVIDER=local
STORAGE_LOCAL_DIR=/app/storage
DEMO_PASSWORD=$demo
MAILBOX_AUTH=demo:$mailbox
EOF
  chmod 600 "$ENV_FILE"
  mkdir -p "$DIR/backups"
}

tunnel_url() { dc logs tunnel 2>/dev/null | grep -oE 'https://[a-z0-9-]+\.trycloudflare\.com' | tail -1 || true; }

wait_for_tunnel() {
  local url=""
  for _ in $(seq 1 60); do
    url=$(tunnel_url)
    [ -n "$url" ] && break
    sleep 2
  done
  [ -n "$url" ] || { echo "The tunnel did not report an address. Check: scripts/staging.sh logs tunnel" >&2; exit 1; }
  echo "$url"
}

wait_for_ready() {
  # The local address uses Caddy's own certificate authority, which this machine does not trust.
  local insecure=""
  [ "$1" = "$LOCAL_URL" ] && insecure="-k"
  for _ in $(seq 1 90); do
    if curl -fsS $insecure --max-time 5 "$1/readyz" >/dev/null 2>&1; then return 0; fi
    sleep 2
  done
  echo "The site did not become ready at $1. Check: scripts/staging.sh logs web" >&2
  exit 1
}

write_access() {
  local url=$1 demo mailbox
  demo=$(get_env DEMO_PASSWORD)
  mailbox=$(get_env MAILBOX_AUTH)
  umask 077
  cat > "$ACCESS" <<EOF
Blooms staging demonstration: private access details.
Keep this to yourself. It is not committed, and nothing here appears in the website's code.
Updated $(date)

Customer view
  Site:            $url/
  Shop:            $url/shop
  Wedding planner: $url/plan
  Order lookup:    $url/track

Owner view (team dashboard)
  Sign in at:      $url/admin
  Email:           owner@demo.example
  Password:        $demo
  Other roles, same password: coordinator@, florist@, sales@, driver@, finance@demo.example

Captured email (Mailpit, never delivered to real inboxes)
  Mailbox:         $url/mailbox/
  User and password: ${mailbox%%:*} / ${mailbox#*:}

Payments are simulated. On the payment page, choose "Pay (simulate success)".
If the tunnel restarts, its address changes: run scripts/staging.sh resync.
EOF
  chmod 600 "$ACCESS"
}

seed_if_empty() {
  local count
  count=$(dc exec -T db psql -U blooms -d blooms -Atc "SELECT count(*) FROM products" 2>/dev/null || echo 0)
  if [ "$count" = "0" ]; then
    echo "Loading fictional demo data..."
    dc exec -T web node dist-server/cli.js seed-demo --stories
  fi
}

case "${1:-}" in
  up)
    ensure_env
    dc build web
    dc up -d db mailpit proxy backup
    dc up -d --force-recreate web worker
    url=$(get_env PUBLIC_BASE_URL)
    wait_for_ready "$url"
    seed_if_empty
    write_access "$url"
    echo ""
    echo "Staging is up at $url"
    [ "$url" = "$LOCAL_URL" ] && echo "It is only reachable from this machine. To reach it from a phone: scripts/staging.sh publish"
    echo "Sign-in details: $ACCESS (readable only by you)"
    ;;
  publish)
    ensure_env
    echo "This makes the staging stack on this machine reachable from the internet through Cloudflare."
    dc up -d tunnel
    url=$(wait_for_tunnel)
    set_env PUBLIC_BASE_URL "$url"
    dc up -d --force-recreate web worker
    wait_for_ready "$url"
    write_access "$url"
    echo "Published at $url. Stop with: scripts/staging.sh unpublish"
    ;;
  unpublish)
    dc stop tunnel
    set_env PUBLIC_BASE_URL "$LOCAL_URL"
    dc up -d --force-recreate web worker
    wait_for_ready "$LOCAL_URL"
    write_access "$LOCAL_URL"
    echo "No longer public. Staging is at $LOCAL_URL"
    ;;
  url)
    get_env PUBLIC_BASE_URL
    ;;
  resync)
    url=$(wait_for_tunnel)
    if [ "$url" != "$(get_env PUBLIC_BASE_URL)" ]; then
      set_env PUBLIC_BASE_URL "$url"
      dc up -d --force-recreate web worker
    fi
    wait_for_ready "$url"
    write_access "$url"
    echo "Staging is at $url"
    ;;
  status)
    dc ps --format '{{.Service}}\t{{.Status}}'
    url=$(get_env PUBLIC_BASE_URL)
    echo "Address: $url"
    curl -s -k --max-time 10 "$LOCAL_URL/readyz" && echo
    ;;
  reset)
    if [ "${2:-}" != "--yes" ]; then
      read -r -p "This deletes all staging data and loads fresh demo data. Type reset to continue: " answer
      [ "$answer" = "reset" ] || { echo "Cancelled."; exit 1; }
    fi
    dc stop web worker
    dc exec -T db psql -U blooms -d postgres -c "DROP DATABASE IF EXISTS blooms WITH (FORCE)" -c "CREATE DATABASE blooms"
    dc up -d web worker
    wait_for_ready "$LOCAL_URL"
    seed_if_empty
    echo "Staging data reset. Delete old messages in the mailbox with its Delete all button."
    ;;
  backup)
    mkdir -p "$DIR/backups"
    file="$DIR/backups/blooms-staging-manual-$(date -u +%Y%m%dT%H%M%SZ).dump"
    dc exec -T db pg_dump -U blooms -d blooms --format=custom --no-owner > "$file.partial"
    mv "$file.partial" "$file"
    echo "$file"
    ;;
  restore-check)
    file=$(ls -t "$DIR"/backups/*.dump 2>/dev/null | head -1)
    [ -n "$file" ] || { echo "No backups yet. Run: scripts/staging.sh backup" >&2; exit 1; }
    pg=$(get_env POSTGRES_PASSWORD)
    dc exec -T db psql -U blooms -d postgres -c "DROP DATABASE IF EXISTS restore_check WITH (FORCE)" -c "CREATE DATABASE restore_check"
    dc exec -T db pg_restore -U blooms -d restore_check --no-owner --exit-on-error < "$file"
    echo "Restored $file into a scratch database. Record checks on the restored copy:"
    dc exec -T -e DATABASE_URL="postgres://blooms:$pg@db:5432/restore_check" web node dist-server/cli.js check
    for t in orders payments wedding_inquiries event_bookings notifications inventory_movements; do
      a=$(dc exec -T db psql -U blooms -d blooms -Atc "SELECT count(*) FROM $t")
      b=$(dc exec -T db psql -U blooms -d restore_check -Atc "SELECT count(*) FROM $t")
      printf '  %-22s live %-6s restored %s\n' "$t" "$a" "$b"
    done
    dc exec -T db psql -U blooms -d postgres -c "DROP DATABASE restore_check WITH (FORCE)" >/dev/null
    ;;
  verify)
    # Checks the running deployment from outside, as a customer and the owner. Credentials are passed
    # through the environment for this run only, and the tests confirm none of them reach the browser.
    url=$(get_env PUBLIC_BASE_URL)
    wait_for_ready "$url"
    secrets=$(printf '%s\n%s\n%s\n%s' "$(get_env DEMO_PASSWORD)" "$(get_env MAILBOX_AUTH | cut -d: -f2-)" "$(get_env SESSION_SECRET)" "$(get_env POSTGRES_PASSWORD)")
    STAGING_URL="$url" STAGING_OWNER_PASSWORD="$(get_env DEMO_PASSWORD)" STAGING_MAILBOX_AUTH="$(get_env MAILBOX_AUTH)" STAGING_SECRET_VALUES="$secrets" \
      npx playwright test -c playwright.staging.config.ts "${@:2}"
    ;;
  logs)
    dc logs -f --tail=100 "${@:2}"
    ;;
  down)
    dc stop
    ;;
  *)
    sed -n '2,20p' "$0"
    exit 1
    ;;
esac
